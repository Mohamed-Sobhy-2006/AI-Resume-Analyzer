
let currentId = null;

if (requireAuth()) init();

async function init() {
  try {
    const resumes = await Api.listResumes();

    if (!resumes.length) {
      $("content").innerHTML = `
        <div class="empty-state card">
          <div class="empty-icon">📄</div>
          <h2>No Resume Found</h2>
          <p class="muted">Upload your resume first to start the AI analysis.</p>
          <a class="btn" href="resume.html">📤 Upload Resume</a>
        </div>
      `;

      $("analyzeBtn").classList.add("hidden");
      return;
    }

    const saved = getResumeId();

    $("resumeSelect").innerHTML = resumes
      .map(
        r => `
          <option value="${r.id}"
            ${String(r.id) === String(saved) ? "selected" : ""}>
            ${esc(r.filename)} (${formatDate(r.uploaded_at)})
          </option>
        `
      )
      .join("");

    $("resumeSelect").addEventListener("change", () => loadAnalysis(false));
    $("analyzeBtn").addEventListener("click", () => loadAnalysis(true));

    loadAnalysis(false);

  } catch (err) {
    showAlert("alert", err.message);
  }
}


async function loadAnalysis(forceRun) {

  currentId = $("resumeSelect").value;
  setResumeId(currentId);

  showAlert("alert", "");

  $("content").innerHTML = loadingHtml("Analyzing your resume with AI...");

  try {

    let analysis;

    if (forceRun) {

      setLoading(
        $("analyzeBtn"),
        true,
        "Analyzing..."
      );

      analysis = await Api.analyzeResume(currentId);

    } else {

      try {

        analysis = await Api.getAnalysis(currentId);

      } catch (e) {

        if (e.status !== 404) throw e;

        analysis = await Api.analyzeResume(currentId);
      }
    }

    const resume = await Api.getResume(currentId);

    render(analysis, resume);

  } catch (err) {

    $("content").innerHTML = "";

    showAlert("alert", err.message);

  } finally {

    setLoading($("analyzeBtn"), false);
  }
}


