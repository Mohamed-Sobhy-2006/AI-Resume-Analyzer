/* -----------------------------------------
   Circular Score
----------------------------------------- */

function scoreCircle(score, label, className = "") {

  score = Math.max(
    0,
    Math.min(
      100,
      Number(score) || 0
    )
  );

  const radius = 54;
  const circumference = 2 * Math.PI * radius;
  const offset =
    circumference -
    (score / 100) * circumference;

  let colorClass = "score-low";

  if (score >= 75) {

    colorClass = "score-good";

  } else if (score >= 50) {

    colorClass = "score-medium";
  }

  return `

    <div class="score-wrapper ${className}">

      <div class="score-circle ${colorClass}">

        <svg viewBox="0 0 130 130">

          <circle
            class="score-bg"
            cx="65"
            cy="65"
            r="${radius}"
          ></circle>

          <circle
            class="score-progress"
            cx="65"
            cy="65"
            r="${radius}"
            stroke-dasharray="${circumference}"
            stroke-dashoffset="${offset}"
          ></circle>

        </svg>

        <div class="score-number">
          ${Math.round(score)}%
        </div>

      </div>

      <span class="score-label">
        ${esc(label)}
      </span>

    </div>

  `;
}


