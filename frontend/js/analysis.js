/* -----------------------------------------
   Resume Score
----------------------------------------- */

function calculateSkillScore(a) {

  const technical =
    Array.isArray(a.technical_skills)
      ? a.technical_skills.length
      : 0;

  const soft =
    Array.isArray(a.soft_skills)
      ? a.soft_skills.length
      : 0;

  const missing =
    Array.isArray(a.missing_skills)
      ? a.missing_skills.length
      : 0;

  const strengths =
    Array.isArray(a.strengths)
      ? a.strengths.length
      : 0;

  /*
   * This is only a visual resume completeness indicator.
   * It is NOT the job matching score.
   */

  const base =
    Math.min(technical * 5, 40) +
    Math.min(soft * 3, 15) +
    Math.min(strengths * 4, 20);

  const penalty =
    Math.min(missing * 3, 25);

  return Math.max(
    0,
    Math.min(
      100,
      base + 25 - penalty
    )
  );
}


/* -----------------------------------------
   Initials
----------------------------------------- */

function getInitials(name) {

  if (!name) return "AI";

  const parts =
    name.trim().split(/\s+/);

  if (parts.length === 1) {

    return parts[0]
      .substring(0, 2)
      .toUpperCase();
  }

  return (
    parts[0][0] +
    parts[parts.length - 1][0]
  ).toUpperCase();
}

