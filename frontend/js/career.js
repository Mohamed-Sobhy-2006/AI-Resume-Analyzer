/* Career Advisor page (RAG-grounded answers). */
if (requireAuth()) init();

async function init() {
  try {
    const resumes = await Api.listResumes();
    if (!resumes.length) { $("content").innerHTML = `<div class="card"><p>Upload a resume first.</p><a class="btn" href="resume.html">Upload</a></div>`; $("askBtn").disabled = true; return; }
    const saved = getResumeId();
    $("resumeSelect").innerHTML = resumes.map(r => `<option value="${r.id}" ${String(r.id) === String(saved) ? "selected" : ""}>${esc(r.filename)}</option>`).join("");
    $("askBtn").addEventListener("click", () => ask($("question").value));
    document.querySelectorAll("[data-q]").forEach(b => b.addEventListener("click", () => { $("question").value = b.dataset.q; ask(b.dataset.q); }));
    const st = await Api.getCareerStatus();
    if (!st.ai_configured) showAlert("alert", "AI service is not configured. Answers are built directly from the retrieved knowledge-base documents.", "warn");
  } catch (err) { showAlert("alert", err.message); }
}

async function ask(question) {
  if (!question.trim()) return showAlert("alert", "Please type a question first.");
  setResumeId($("resumeSelect").value);
  showAlert("alert", "");
  $("content").innerHTML = loadingHtml("Retrieving knowledge and preparing advice...");
  setLoading($("askBtn"), true, "Thinking...");
  try { render(await Api.getCareerAdvice(Number($("resumeSelect").value), question)); }
  catch (err) { $("content").innerHTML = ""; showAlert("alert", err.message); }
  finally { setLoading($("askBtn"), false); }
}

function resourceList(items) {
  if (!items || !items.length) return `<p class="muted">None found</p>`;
  return `<ul class="clean">${items.map(r => `<li><strong>${esc(r.title)}</strong>${r.skill ? ` <span class="chip">${esc(r.skill)}</span>` : ""}<br>
    <span class="muted">${esc(r.description || "")}</span>${r.url ? `<br><a href="${esc(r.url)}" target="_blank" rel="noopener noreferrer">${esc(r.url)}</a>` : ""}</li>`).join("")}</ul>`;
}

function render(r) {
  if (r.notice) showAlert("alert", r.notice, r.grounded ? "warn" : "info");
  else if (r.ai_generated) showAlert("alert", "Answer generated by Gemini using the retrieved knowledge base.", "success");
  if (!r.grounded) { $("content").innerHTML = `<div class="card"><h2>Answer</h2><p>${esc(r.answer)}</p></div>`; return; }
  $("content").innerHTML = `
    <div class="card"><h2>Answer</h2><p>${esc(r.answer)}</p></div>
    <div class="card"><h3>RAG retrieval - ${r.retrieved_context_count} chunk(s) used as context (top-K)</h3>
      <table><tr><th>Document</th><th>Category</th><th>Similarity</th></tr>${r.sources.map(s => `<tr><td>${esc(s.title)}</td><td>${esc(s.category)}</td><td>${s.score}</td></tr>`).join("")}</table></div>
    <div class="grid cols-2">
      <div class="card"><h3>Recommended skills</h3>${chips(r.recommended_skills, "miss")}</div>
      <div class="card"><h3>Career roadmap</h3>${bullets(r.roadmap)}</div>
      <div class="card"><h3>Certifications</h3>${resourceList(r.certifications)}</div>
      <div class="card"><h3>Learning resources</h3>${resourceList(r.learning_resources)}</div>
    </div>
    <div class="card"><h3>Resume improvements</h3>${bullets(r.resume_improvements)}</div>`;
}
